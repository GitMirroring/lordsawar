void Startup::load_saved_game (std::string load_filename)
{
  initialize ();
  bool broken = false;
  Glib::ustring err;
  GameScenario* g = new GameScenario (load_filename, broken, err);
  if (!broken)
    {
      if (g->getPlayMode () == GameScenario::HOTSEAT)
        {
          NextTurn *next_turn = new NextTurnHotseat ();
          setup_game_window (true);
          m_signal_game_window_coming_up.emit ();
          m_game_window->load_game (g, next_turn);
        }
    }
}

