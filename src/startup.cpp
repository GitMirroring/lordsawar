void Startup::server (std::string load_filename)
{
  Lw::loop = Glib::MainLoop::create ();

  auto profile = Profilelist::instance ()->getAdminProfile ();
  if (!profile)
    profile =
      Profilelist::instance ()->findLastPlayedProfileForUser
      (Glib::get_user_name ());
  if (!profile && Profilelist::instance ()->empty () == false)
    profile = Profilelist::instance ()->front ();
  if (!profile && Profilelist::instance ()->empty () == true)
    profile = Profilelist::createAdminProfile ();

  if (load_filename.empty () == true)
    {
      GameParameters g;
      //for (unsigned int i = 0; i < MAX_PLAYERS; i++)
      for (unsigned int i = 0; i < 3; i++)
        {
          GameParameters::Player p;
          p.type = GameParameters::Player::HUMAN;
          p.id = i;
          p.name = CreateScenarioRandomize::getPlayerName (Shield::Color (i)); 
          g.players.push_back (p);
        }
      g.map.width = MAP_SIZE_NORMAL_WIDTH;
      g.map.height = MAP_SIZE_NORMAL_HEIGHT;
      g.map.grass = 78;
      g.map.water = 7;
      g.map.swamp = 2;
      g.map.forest = 3;
      g.map.hills = 5;
      g.map.mountains = 5;
      g.map.cities = 80;
      g.map.ruins = 15;
      g.map.temples = 3;
      g.map.signposts = 20;
      g.map_path = "";
      g.play_with_quests = GameParameters::ONE_QUEST_PER_PLAYER;
      g.hidden_map = false;
      g.neutral_cities = GameParameters::STRONG;
      g.razing_cities = GameParameters::ALWAYS;
      g.diplomacy = false;
      g.random_turns = false;
      g.quick_start = GameParameters::NO_QUICK_START;
      g.intense_combat = false;
      g.military_advisor = false;
      for (guint32 i = 0; i < MAX_PLAYERS + 1; i++)
        g.army_theme[i] = "default";
      g.tile_theme = "default";
      g.shield_theme = "default";
      g.city_theme = "default";
      g.cities_can_produce_allies = false;
      g.cusp_of_war = false;
      g.see_opponents_stacks = false;
      g.see_opponents_production = false;
      g.vectoring_mode = GameParameters::VECTORING_ALWAYS_TWO_TURNS;
      g.build_production_mode = GameParameters::BUILD_PRODUCTION_ALWAYS;
      g.sacking_mode = GameParameters::SACKING_ALWAYS;
      g.difficulty = GameScenario::calculate_difficulty_rating (g);
      g.name = _("Autogenerated");
      g.comment = "This is a randomly generated scenario.";

      std::string path = File::get_tmp_file (MAP_EXT);
      GameScenario::create_and_dump
        (path, g, NULL,
         [this, g, profile, path] ()
         {
           bool broken = false;

           Glib::ustring err = "";
           auto game_scenario = new GameScenario (path, broken, err);
           if (!broken)
             serve (game_scenario, g, Lw::app->m_port ?
                    Lw::app->m_port : LORDSAWAR_PORT, profile, true);
           else
             {
               std::cerr <<
                 String::ucompose (_("%1: could not load `%2'.  %3"),
                                   Lw::get_prgname (), path, err) <<
                 std::endl;
               exit (1);
             }
         });
    }
  else
    {
      bool broken = false;
      GameParameters g = GameScenario::loadGameParameters (load_filename,
                                                           broken);
      if (!broken)
        {
          Glib::ustring err = "";
          auto game_scenario = new GameScenario (load_filename, broken, err);
          if (!broken)
            serve (game_scenario, g, Lw::app->m_port ?
                   Lw::app->m_port : LORDSAWAR_PORT, profile, true);
          else
            {
              std::cerr <<
                String::ucompose (_("%1: could not load `%2'.  %3"),
                                  Lw::get_prgname (), load_filename, err) <<
                std::endl;
              exit (1);
            }
        }
      else
        {
          std::cerr <<
            String::ucompose (_("%1: could not load `%2'."),
                              Lw::get_prgname (), load_filename) <<
            std::endl;
          exit (1);
        }

    } 

  Lw::app->hold ();
  Lw::loop->run ();
}

void Startup::hotseat_game (GameScenario *g)
{
  NextTurn *next_turn = new NextTurnHotseat ();
  setup_game_window (true);
  m_game_window->new_game (g, next_turn);
  m_signal_game_window_coming_up.emit ();
}

void Startup::setup_hotseat_game (Gtk::ApplicationWindow *parent)
{
  auto d = LwDialog::build<ChooseScenarioDialog> (parent);
  d->setup ();
  d->signal_scenario_selected ().connect
    ([this, d] (ScenarioDetails *scen)
     {
       if (scen)
         setup_scenario (scen->get_filename (), GameScenario::HOTSEAT, d);
       else
         {
           //if scenario is null it means we want a random map
           auto dd = LwDialog::build<NewRandomMapDialog> (d);
           dd->setup ();
           dd->signal_scenario_generated ().connect
             ([this, d, dd] (std::string filename, GameScenario::PlayMode m)
              {
                setup_scenario (filename, m, d);
              });
           dd->signal_response ().connect
             ([d] (Gtk::ResponseType resp)
              {
                if (resp != Gtk::ResponseType::ACCEPT)
                  delete d;
                // otherwise this dialog gets deleted when the game window is
                // coming up
              });
         }
     });
  d->signal_response ().connect
    ([d] (Gtk::ResponseType resp)
     {
       if (resp != Gtk::ResponseType::ACCEPT)
         delete d;
       //otherwise we delete when the game window is coming up
     });
}

void Startup::initialize ()
{
  if (m_initialized)
    return;
  if (Lw::app->m_configuration_file_path != "")
    Configuration::s_configuration_file_path = Lw::app->m_configuration_file_path;
  if (Lw::app->m_save_path != "")
    Configuration::s_savePath = Lw::app->m_save_path;
  initialize_configuration ();
  if (Lw::app->m_cacheSize)
    Configuration::s_cacheSize = Lw::app->m_cacheSize;
  Profilelist::support_backward_compatibility ();
  RecentlyPlayedGameList::support_backward_compatibility ();
  Gamelist::support_backward_compatibility ();
  FileCompat::support_backward_compatibility_for_common_files ();
  FileCompat::instance ()->initialize ();
  RecentlyPlayedGameList::instance ()->load ();

  // Check if armysets are in the path (otherwise exit)
  Armysetlist::scan (Armyset::file_extension);
  Tilesetlist::scan (Tileset::file_extension);
  Shieldsetlist::scan (Shieldset::file_extension);
  Citysetlist::scan (Cityset::file_extension);
  m_initialized = true;
}

void Startup::run_stress_test (GameScenario *game_scenario, std::string path)
{
  NextTurnHotseat *nextTurn = new NextTurnHotseat ();

  nextTurn->snextRound.connect
    ([] ()
     {
       static int count = 1;
       count++;
       std::cout <<
         String::ucompose ("%1: starting round %2!",
                           Lw::get_prgname (), count) << std::endl;
     });

  auto game = new Game (game_scenario, nextTurn);

  game->get_smallmap ().set_slide_speed (0);
  Configuration::s_displaySpeedDelay = 0;
  time_t start = time (NULL);
  nextTurn->start ();
  nextTurn->signal_game_over ().connect
    ([game, start, game_scenario, path] ()
     {
       File::erase (path);
       //next turn and game_Scenario get deleted inside game.
       double mins = (time (NULL) - start) / 60.0;
       printf ("seed: %d, duration: %.2lf mins, turns: %d ",
               Lw::app->m_random_number_seed, mins, game_scenario->getRound ());
       printf ("winner type: %s\n",
               Player::playerTypeToString
               (Playerlist::instance ()->getFirstLiving ()->getType ()).c_str ());
       Glib::ustring s =
         File::getTempFile (File::getCacheDir (),
                            String::ucompose ("run-seed-%1",
                                              Lw::app->m_random_number_seed)) +
         SAVE_EXT;
       game_scenario->saveGame (s);
       delete game;

       Lw::quit_loop ();
     });
}

