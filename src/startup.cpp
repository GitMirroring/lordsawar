void Startup::client (Gtk::ApplicationWindow *parent, Glib::ustring host,
                      unsigned short port, Profile *p)
{
  Lobby::deleteInstance ();
  Lobby::instance ()->set_profile (p->getId ());
  Lobby::instance ()->join (p->getId (), p->getNickname ());
  GameClient::deleteInstance ();
  GameClient *game_client = GameClient::instance ();
  game_client->signal_game_scenario_received ().connect
    ([this, host, port, p, game_client, parent] (std::string path)
     {
       m_download_window->hide ();
       delete m_download_window;
       m_download_window = NULL;
        
       auto w = Gtk::make_managed<EditorLoadWindow> ();
       w->setup ();
       w->present ();
       w->set_modal (true);
       w->set_transient_for (*m_splash_window);

       sigc::connection load_tick_conn;
       load_tick_conn = GameScenario::load_tick.connect
         ([this, w, load_tick_conn] (double fraction) mutable
          {
            if (w)
              {
                w->set_fraction (fraction);
                Lw::do_events ();
              }
            else
              load_tick_conn.disconnect ();
          });
       //a path to our downloaded game scenario
       //the scenario comes over the line pre-initialized
       bool broken = false;
       Glib::ustring err;
       GameScenario* game_scenario = new GameScenario (path, broken, err);
       load_tick_conn.disconnect ();
       delete w;
       w = NULL;
       if (!broken)
         {
           auto recent = RecentlyPlayedGameList::instance ();
           recent->addNetworkedEntry (game_scenario, p, host, port);
           recent->save ();

           broken = false;

           start_game_lobby_for_client (parent, game_scenario);
         }
     });

  game_client->signal_logged_in_as_same_profile_id ().connect
    ([this] ()
     {
       hide_download_window ();
       auto dialog = LwDialog::alert (_("Could not connect"),
                                      _("Same profile id is logged in."));
       dialog->choose
         (*m_splash_window,
          [dialog] (auto result)
          {
            dialog->choose_finish (result);
            return;
          });
     });

  game_client->signal_client_disconnected ().connect
    ([] ()
     {
       GameClient::deleteInstance ();
       Lw::app->quit ();
     });

  game_client->signal_client_forcibly_disconnected ().connect
    ([this] ()
     {
       hide_download_window ();
       if (m_game_lobby_dialog)
         m_game_lobby_dialog->hide ();
       auto dialog = LwDialog::alert (_("Server disconnected"), "");
       dialog->choose
         (*m_splash_window,
          [dialog] (auto result)
          {
            dialog->choose_finish (result);
            return;
          });
     });

  game_client->signal_client_could_not_connect ().connect
    ([this] ()
     {
       hide_download_window ();
       auto dialog = LwDialog::alert (_("Could not connect"),
                                      _("Server could not be contacted."));
       dialog->choose
         (*m_splash_window,
          [dialog] (auto result)
          {
            dialog->choose_finish (result);
            return;
          });
     });

  game_client->signal_client_connected ().connect
    ([this, game_client, parent] ()
     {
       hide_download_window ();
       m_download_window = new NetworkGameDownloadWindow ();
       m_download_window->setup ();
       m_download_window->set_transient_for (*parent);
       m_download_window->present ();

       game_client->signal_payload_progress ().connect
         ([this] (int numerator, int denominator)
          {
            if (!m_download_window)
              return;
            double fraction = (double)numerator / (double)denominator;
            if (fraction < 1)
              m_download_window->set_fraction (fraction);
          });
     });

  game_client->start (host, port, p->getId (), p->getNickname ());
}

void Startup::hide_download_window ()
{
  if (m_download_window)
    delete m_download_window;
  m_download_window = NULL;
}

void Startup::setup_game_window (bool show)
{
  m_game_window = Gtk::make_managed<GameWindow> ();
  Lw::app->add_window (*m_game_window);
  m_game_window->signal_game_ended_start_new ().connect
    ([this, show] ()
     {
       delete m_game_window;
       
       Lw::app->add_window (*m_splash_window);
       if (show)
         m_splash_window->present ();
     });
  m_game_window->signal_show_lobby ().connect
    ([this] ()
     {
       if (m_game_lobby_dialog)
         m_game_lobby_dialog->show ();
     });
       
  if (show)
    m_game_window->show ();
}

void Startup::setup_splash_window ()
{
  m_splash_window = Gtk::make_managed<SplashWindow>();
  Lw::app->add_window (*m_splash_window);
  m_splash_window->present ();
  m_splash_window->signal_setup_hotseat_game ().connect
    ([this] (Gtk::ApplicationWindow *parent)
     {
       setup_hotseat_game (parent);
     });

  m_splash_window->signal_scenario_builder ().connect
    ([this] ()
     {
       m_splash_window->hide ();
       //editor (""); compiletimefix
     });

  m_splash_window->signal_load_game ().connect
    ([this] (Gtk::ApplicationWindow *parent, std::string filename)
     {
       (void) parent;
       load_saved_game (filename);
     });

  m_splash_window->signal_setup_net_client ().connect
    ([this] (Gtk::ApplicationWindow *parent, Glib::ustring host,
             unsigned short port, Profile *profile)
     {
       client (parent, host, port, profile);
     });

  m_splash_window->signal_setup_net_server ().connect
    ([this] (Gtk::ApplicationWindow *parent, Profile *profile)
     {
       server (parent, profile);
     });

  signal_game_window_coming_up ().connect
    ([this] ()
     {
       m_splash_window->hide ();
     });
}

void Startup::serve (GameScenario *game_scenario, GameParameters g, int port,
                     Profile *profile, bool mod_first_participant)
{
  Lobby::deleteInstance ();
  Lobby::instance ()->join (profile->getId (), profile->getNickname ());
  Lobby::instance ()->set_profile (profile->getId ());
  Lobby::instance ()->add_mod (profile->getId ());
  game_scenario->setPlayMode (GameScenario::NETWORKED);
  game_scenario->initialize (g);

  Playerlist::instance ()->syncNeutral ();

  GameServer *game_server = GameServer::instance ();
  if (Lw::app->m_save_server_messages != "")
    game_server->saveMessages (Lw::app->m_save_server_messages);
  game_server->signal_port_in_use ().connect
    ([] (int p)
     {
       std::cerr <<
         String::ucompose (_("%1: couldn't bind to port %2."),
                           Lw::get_prgname (), p) << std::endl;
       Lw::app->quit ();
       exit (1);
     });
  Glib::ustring id = "";

  game_server->start (game_scenario, port, profile->getId (),
                      profile->getNickname ());
  game_server = GameServer::instance ();
  if (game_server->isRunning () == false)
    {
      GameServer::deleteInstance ();
      return;
    }

  std::cout <<
    String::ucompose (_("%1: game server is now listening on port %2."),
                      Lw::get_prgname (), port) << std::endl;
  auto next_turn = new NextTurnNetworked ();
  game_server->signal_round_ends ().connect
    (sigc::mem_fun (*next_turn, &NextTurnNetworked::finishRound));
  game_server->signal_start_player_turn ().connect
    (sigc::mem_fun (*next_turn, &NextTurnNetworked::start_player));
  next_turn->srequestAbort.connect
    (sigc::mem_fun (*game_server, &GameServer::on_turn_aborted));
  game_server->signal_get_next_player ().connect
    (sigc::mem_fun (*next_turn, &NextTurnNetworked::next));

  game_server->signal_countdown ().connect
    ([this, next_turn] (guint32 secs_left)
     {
       if (secs_left == 0)
         next_turn->start ();
     });

  if (mod_first_participant)
    {
      game_server->signal_remote_participant_joins ().connect
        ([] (Glib::ustring mid, bool)
         {
           if (Lobby::instance ()->count_mods () <= 1)
             GameServer::instance ()->add_mod (mid);
         });
    }

  next_turn->m_signal_player_died.connect
    ([] (Player *p, std::shared_ptr<sigc::slot<void()>> after)
     {
       GameServer::instance ()->sendKillPlayer (p);
       if (after)
         (*after) ();
     });
  

  Configuration::s_autosave_policy = Configuration::NO_AUTOSAVING;
  auto game = new Game (game_scenario, next_turn, true);
  game->signal_game_over ().connect
    ([game_scenario] (Player *p, sigc::slot<void()> )
     {
       std::cout <<
         String::ucompose (_("%1: all done!  `%2' was the winner on turn %3."),
                           Lw::get_prgname (), p->getName (),
                           game_scenario->getRound ()) << std::endl;

       GameServer::deleteInstance ();
       exit (0);
     });

}
    
void Startup::start_game_lobby_for_client (Gtk::ApplicationWindow *parent,
                                           GameScenario *game_scenario)
{
  auto game_client = GameClient::instance ();

  game_client->request_seat_manifest ();
  Lobby::instance ()->add_chat_message
    ("", game_scenario->getName ());
  if (game_scenario->getComment () != "")
    Lobby::instance ()->add_chat_message
      ("", game_scenario->getComment ());
  int city_count = Citylist::instance ()->size ();
  int ruin_count = Ruinlist::instance ()->countUnhiddenRuins ();
  int temple_count = Templelist::instance ()->size ();
  Glib::ustring city = ngettext ("city", "cities", city_count);
  Glib::ustring ruin = ngettext ("ruin", "ruins", ruin_count);
  Glib::ustring temple = ngettext ("temple", "temples", temple_count);
  Lobby::instance ()->add_chat_message
    ("",
     String::ucompose
     (_("The scenario has %1 %2, %3 %4 and %5 %6."),
      city_count, city, ruin_count, ruin, temple_count, temple));

  NextTurnNetworked *next_turn = new NextTurnNetworked ();
  // game_client signal_start_player_turn -> next turn start_player
  // happens in game-window

  setup_game_window (false);

  m_game_window->new_network_game (game_scenario, next_turn);

  m_game_window->signal_show_lobby ().connect
    ([this] ()
     {
       m_game_lobby_dialog->show ();
     });

  GameClient::instance ()->signal_game_begin ().connect
    ([this] ()
     {
       m_game_lobby_dialog->set_transient_for (*m_game_window);
       m_game_window->show ();
       m_game_lobby_dialog->set_modal (false);
       m_game_lobby_dialog->hide ();
       m_game_lobby_dialog->start_game ();
       m_signal_game_window_coming_up.emit ();
     });

  m_game_lobby_dialog = LwDialog::build<GameLobbyDialog> (parent);
  m_game_lobby_dialog->setup (game_scenario, false);
  m_game_lobby_dialog->present ();
  m_game_lobby_dialog->signal_response ().connect
    ([this, game_scenario, game_client](Gtk::ResponseType resp)
     {
       if (game_scenario->getRound () == 0)
         {
          switch (resp)
             {
             case Gtk::ResponseType::CANCEL: // either cancel or close
             case Gtk::ResponseType::DELETE_EVENT:
             default:
               m_game_lobby_dialog->hide ();
               game_client->disconnect ();
               GameClient::deleteInstance ();
               break;
             }
         }
     });
}

